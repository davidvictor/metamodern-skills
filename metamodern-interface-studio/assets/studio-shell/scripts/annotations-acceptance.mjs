#!/usr/bin/env node
/** Focused local-only annotation journey. No fixed sleeps, network send, screenshots or product fixtures. */
import assert from "node:assert/strict"
import { spawn } from "node:child_process"
import { writeFileSync } from "node:fs"
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? "playwright")
const started = performance.now()
const server = spawn(process.execPath, ["node_modules/vite/bin/vite.js", "--host", "127.0.0.1", "--port", "0"], { cwd: process.cwd(), env: { ...process.env, VITE_STUDIO_ADAPTER: "library", STUDIO_LOCAL_ANNOTATIONS: "1", NO_COLOR: "1" }, stdio: ["ignore", "pipe", "pipe"] })
const url = await new Promise((resolve, reject) => {
  const timer = setTimeout(() => reject(new Error("Local Studio server did not start")), 30000)
  let output = ""
  const read = data => { output += data; const match = output.match(/http:\/\/127\.0\.0\.1:\d+\//); if (match) { clearTimeout(timer); resolve(match[0]) } }
  server.stdout.on("data", read); server.stderr.on("data", read)
  server.once("exit", code => { clearTimeout(timer); reject(new Error(`Server exited ${code}: ${output.slice(-2000)}`)) })
})
const browser = await chromium.launch({ headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, permissions: ["clipboard-read", "clipboard-write"] })
const page = await context.newPage()
const errors = [], requests = [], checks = []
page.on("pageerror", error => errors.push(error.message))
page.on("console", message => { if (message.type() === "error") errors.push(message.text()) })
page.on("request", request => requests.push(request.url()))
const passed = label => checks.push(label)
const countRuntimes = async () => (await Promise.all(page.frames().map(frame => frame.locator("[data-studio-annotation-runtime]").count()))).reduce((a, b) => a + b, 0)
const note = async (document, target, comment) => {
  await document.locator("agentation-toolbar").waitFor({ state: "attached" })
  await document.getByRole("button", { name: "Start feedback mode", exact: true }).click()
  await target.click()
  await document.getByPlaceholder("What should change?").fill(comment)
  await document.getByRole("button", { name: "Add", exact: true }).click()
}
try {
  await page.goto(`${url}#view=compare`)
  await page.getByRole("button", { name: "Compare", exact: true }).waitFor()
  assert.equal(await page.locator("[data-studio-annotations]").count(), 0)
  assert.equal(await countRuntimes(), 0)
  assert.equal(requests.filter(value => /annotations\/runtime|\/agentation(?:[./?]|$)/.test(value)).length, 0)
  passed("Cold excluded page fetches no Agentation and mounts no runtime")
  const settleDrawer = screen => screen.evaluate(async () => {
    await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))
    const drawer = document.querySelector('[role="dialog"]')
    await Promise.all((drawer?.getAnimations({ subtree: true }) ?? []).filter(animation => Number.isFinite(animation.effect?.getComputedTiming().endTime)).map(animation => animation.finished.catch(() => undefined)))
    await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))
  })
  for (const appearance of ["light", "dark"]) for (const [width, height] of [[768, 1024], [1024, 768], [390, 844]]) {
    const touch = await browser.newContext({ viewport: { width, height }, hasTouch: true, isMobile: true, colorScheme: appearance })
    await touch.addInitScript(value => localStorage.setItem("studio.appearance", value), appearance)
    const screen = await touch.newPage()
    screen.on("request", request => requests.push(request.url()))
    screen.on("pageerror", error => errors.push(error.message))
    screen.on("console", message => { if (message.type() === "error") errors.push(message.text()) })
    await screen.goto(`${url}#view=inspect&scenario=tasks.list`)
    await screen.locator('agentation-toolbar').waitFor({ state: 'attached' })
    await screen.locator('[data-studio-preview-controls="dock"], [data-studio-bottom-controls]').waitFor()
    await screen.waitForFunction(() => {
      const dock = document.querySelector('[data-studio-preview-controls="dock"], [data-studio-bottom-controls]')?.getBoundingClientRect()
      const sdk = document.querySelector('agentation-toolbar')?.shadowRoot?.querySelector('[data-agentation-toolbar]')?.getBoundingClientRect()
      const panel = document.querySelector('[data-studio-annotations]')?.getBoundingClientRect()
      return dock && sdk && panel && sdk.bottom <= dock.top && panel.bottom <= sdk.top && panel.left >= 0 && panel.right <= innerWidth
    })
    const reached = await screen.evaluate(() => [...document.querySelectorAll('[data-studio-preview-controls="dock"] button, [data-studio-bottom-controls] button')].filter(e => { const r = e.getBoundingClientRect(); return r.width && r.height && !e.disabled }).every(e => { const r = e.getBoundingClientRect(); return e.contains(document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2)) }))
    assert.ok(reached, `Studio dock buttons remain on top at ${width}x${height}`)
    if (width === 768) {
      if (await screen.getByRole("button", { name: "More actions", exact: true }).count()) await screen.getByRole("button", { name: "More actions", exact: true }).click()
      const generation = await screen.locator('[data-studio-annotation-runtime]').getAttribute('data-studio-annotation-runtime')
      await screen.getByRole("button", { name: "Studio settings", exact: true }).click()
      await screen.getByText("Stage toolbar", { exact: true }).click()
      await screen.locator('[data-studio-preview-controls="dock"]').waitFor({ state: "detached" })
      await screen.keyboard.press("Escape")
      await screen.getByRole("button", { name: "Studio settings", exact: true }).click()
      await screen.getByText("Floating dock", { exact: true }).click()
      await screen.locator('[data-studio-preview-controls="dock"]').waitFor()
      await screen.keyboard.press("Escape")
      await screen.waitForFunction(() => {
        const dock = document.querySelector('[data-studio-preview-controls="dock"]')?.getBoundingClientRect()
        const sdk = document.querySelector('agentation-toolbar')?.shadowRoot?.querySelector('[data-agentation-toolbar]')?.getBoundingClientRect()
        return dock && sdk && sdk.bottom <= dock.top
      })
      assert.equal(await screen.locator('[data-studio-annotation-runtime]').getAttribute('data-studio-annotation-runtime'), generation, "Controls placement changes preserve the host capture session")
    }
    if (width === 390) {
      await screen.getByRole("button", { name: "Panel", exact: true }).click()
      await screen.locator('[role="dialog"]').waitFor()
      await settleDrawer(screen)
      await screen.waitForFunction(() => {
        const dialog = document.querySelector('[role="dialog"]')?.getBoundingClientRect()
        const sdk = document.querySelector('agentation-toolbar')?.shadowRoot?.querySelector('[data-agentation-toolbar]')?.getBoundingClientRect()
        return dialog && sdk && sdk.bottom <= dialog.top
      })
      await note(screen, screen.getByRole("dialog").getByRole("button", { name: "All", exact: true }), "Drawer wrapper recreation preserves this accepted note.")
      await screen.getByRole("button", { name: "Exit", exact: true }).click()
      await screen.keyboard.press("Escape")
      await screen.locator('[role="dialog"]').waitFor({ state: "detached" })
      await screen.getByRole("button", { name: "Feedback (1)", exact: true }).waitFor()
      await screen.getByRole("button", { name: "Start feedback mode", exact: true }).waitFor()
      await screen.waitForFunction(() => Object.keys(localStorage).filter(key => key.startsWith("feedback-annotations-")).some(key => localStorage.getItem(key)?.includes("Drawer wrapper recreation preserves this accepted note.")))
      await screen.getByRole("button", { name: "Details", exact: true }).click()
      await screen.getByRole("dialog").waitFor()
      await settleDrawer(screen)
      const next = screen.getByRole("dialog").getByRole("button", { name: "Next scenario", exact: true })
      assert.ok(await next.evaluate(element => { const box = element.getBoundingClientRect(); for (let y = box.top + 0.25; y < box.bottom; y += 0.25) if (!element.contains(document.elementFromPoint(box.x + box.width / 2, y))) return false; return true }), "Details Next scenario retains its full vertical touch target after the sheet transform settles")
      await screen.keyboard.press("Escape")
      await screen.getByRole("dialog").waitFor({ state: "detached" })
      await screen.goto(`${url}#library=button`)
      await screen.getByRole("heading", { name: "Button", exact: true }).waitFor()
      await screen.locator('[data-studio-bottom-navigation]').waitFor()
      await screen.locator('agentation-toolbar').waitFor({ state: 'attached' })
      await screen.waitForFunction(() => {
        const nav = document.querySelector('[data-studio-bottom-navigation]')?.getBoundingClientRect()
        const sdk = document.querySelector('agentation-toolbar')?.shadowRoot?.querySelector('[data-agentation-toolbar]')?.getBoundingClientRect()
        return nav && sdk && sdk.bottom <= nav.top
      })
    }
    await touch.close()
  }
  passed("Host SDK and target controls clear the wrapped dock at tablet, landscape and phone widths")
  await page.goto(url)
  await page.locator("agentation-toolbar").waitFor({ state: "attached" })
  await page.evaluate(() => {
    const group = document.createElement("section"); group.id = "privacy-proof"; group.style.cssText = "position:fixed;left:500px;top:300px;z-index:99999;background:white;padding:20px";
    group.innerHTML = '<button id="public-neighbor">Public neighbor</button><button data-private id="private-proof">PM29 PRIVATE SECRET</button>';
    document.body.append(group)
  })
  for (const selector of ["#private-proof", "#public-neighbor"]) {
    await page.getByRole("button", { name: "Start feedback mode", exact: true }).click()
    assert.ok(await page.locator(selector).isVisible())
    // Vendor animation freezing can stall actionability RAFs; this visible synthetic target has fixed coordinates.
    await page.locator(selector).click({ force: true })
    await page.getByRole("button", { name: "Start feedback mode", exact: true }).waitFor()
    const vendor = await page.evaluate(() => Object.keys(localStorage).filter(key => key.startsWith("feedback-annotations-")).map(key => localStorage.getItem(key)).join(""))
    assert.ok(!vendor.includes("PM29 PRIVATE SECRET"))
    assert.equal(await page.getByPlaceholder("What should change?").count(), 0)
  }
  await page.evaluate(() => document.getElementById("privacy-proof").remove())
  passed("Private targets and private-neighbor capture are blocked before vendor storage")
  await note(page, page.getByText("Catalog", { exact: true }), "Studio shell note.\nKeep this line verbatim.")
  await page.getByRole("button", { name: "Feedback (1)", exact: true }).waitFor()
  assert.equal(await countRuntimes(), 1)
  passed("Studio note has one runtime")
  const select = page.getByLabel("Annotation target")
  await page.waitForFunction(() => [...(document.querySelector('select[aria-label="Annotation target"]')?.options ?? [])].some(option => option.value !== "studio" && !option.disabled))
  await select.selectOption(await select.locator('option:not([disabled]):not([value="studio"])').first().getAttribute("value"))
  const preview = page.frame({ name: await select.inputValue() })
  assert.ok(preview, "Selected Inspect frame is live")
  await note(preview, preview.locator("h1"), "Product preview note.")
  await page.getByRole("button", { name: "Feedback (2)", exact: true }).waitFor()
  assert.equal(await page.locator("[data-studio-annotation-runtime]").count(), 0)
  assert.equal(await countRuntimes(), 1)
  passed("Selected preview replaces the host runtime")
  const originalPreview = await preview.evaluate(() => ({ width: innerWidth, mounts: window.__studioMounts }))
  const oldPreviewGeneration = await preview.locator("[data-studio-annotation-runtime]").getAttribute("data-studio-annotation-runtime")
  await page.getByRole("slider", { name: "Frame width", exact: true }).press("ArrowRight")
  await preview.waitForFunction(old => { const runtime = document.querySelector("[data-studio-annotation-runtime]"); return runtime && runtime.getAttribute("data-studio-annotation-runtime") !== old }, oldPreviewGeneration)
  await preview.locator("agentation-toolbar").waitFor({ state: "attached" })
  assert.equal(await preview.evaluate(() => window.__studioMounts), originalPreview.mounts)
  const capturedWidth = await page.evaluate(() => {
    const key = Object.keys(localStorage).find(value => value.startsWith("studio-feedback/1:") && !value.endsWith(":enabled"))
    return JSON.parse(localStorage.getItem(key)).find(note => note.session.context.layer === "preview").session.context.viewport.width
  })
  assert.equal(capturedWidth, originalPreview.width)
  passed("Selected preview context updates revoke its session without membership churn or capture mutation")
  await select.selectOption("studio")
  await page.locator("agentation-toolbar").waitFor({ state: "attached" })
  const oldStudioGeneration = await page.locator("[data-studio-annotation-runtime]").getAttribute("data-studio-annotation-runtime")
  await page.getByRole("slider", { name: "Frame width", exact: true }).press("ArrowRight")
  await page.waitForFunction(old => { const runtime = document.querySelector("[data-studio-annotation-runtime]"); return runtime && runtime.getAttribute("data-studio-annotation-runtime") !== old }, oldStudioGeneration)
  await page.locator("agentation-toolbar").waitFor({ state: "attached" })
  assert.equal(await page.evaluate(async () => (await import("/src/studio/location.ts")).committedStudioLocation()), await page.evaluate(() => location.hash))
  assert.equal(await countRuntimes(), 1)
  passed("Studio session follows the canonical committed URL without incidental preview-context notifications")
  await page.getByRole("button", { name: "Feedback (2)", exact: true }).click()
  await page.getByLabel("Combined feedback Markdown").waitFor()
  assert.equal(await countRuntimes(), 0)
  const markdown = await page.getByLabel("Combined feedback Markdown").inputValue()
  assert.ok(markdown.includes("Studio shell note.\nKeep this line verbatim."))
  assert.ok(markdown.includes("Product preview note."))
  assert.ok(markdown.includes("example/studio-source"))
  assert.ok(markdown.includes("Scope: example"))
  await page.getByRole("button", { name: "Copy feedback", exact: true }).click()
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), markdown)
  passed("Review suspends inspection and copies enriched combined feedback")
  await page.evaluate(() => Object.defineProperty(navigator.clipboard, "writeText", { configurable: true, value: async () => { throw new DOMException("Clipboard blocked for proof", "NotAllowedError") } }))
  await page.getByRole("button", { name: "Copy feedback", exact: true }).click()
  const recovery = page.getByRole("dialog").getByRole("status").filter({ hasText: "Clipboard unavailable" })
  await recovery.waitFor()
  assert.ok(await recovery.isVisible())
  assert.equal(await page.getByLabel("Combined feedback Markdown").inputValue(), markdown)
  await page.getByLabel("Combined feedback Markdown").evaluate(element => { element.focus(); element.select() })
  assert.equal(await page.getByLabel("Combined feedback Markdown").evaluate(element => element.selectionEnd - element.selectionStart), markdown.length)
  await recovery.getByRole("button", { name: "Dismiss", exact: true }).click()
  await recovery.waitFor({ state: "detached" })
  assert.equal(await page.getByRole("dialog").getByRole("status").filter({ hasText: "Clipboard unavailable" }).count(), 0)
  passed("Clipboard refusal is announced inside review with selectable intact feedback and accessible recovery")
  await page.getByLabel("Change scope for h1").selectOption("shared")
  assert.ok((await page.getByLabel("Combined feedback Markdown").inputValue()).includes("Scope: shared"))
  await page.getByRole("button", { name: "Close", exact: true }).click()
  await page.goto(`${url}#library=button`)
  await page.getByRole("button", { name: /Expand/ }).first().click()
  await page.getByRole("dialog").waitFor()
  await page.waitForFunction(() => [...(document.querySelector('select[aria-label="Annotation target"]')?.options ?? [])].some(option => option.textContent.includes("(expanded preview)") && !option.disabled))
  const expandedSelect = page.getByLabel("Annotation target")
  await expandedSelect.selectOption(await expandedSelect.locator("option:not([disabled])").filter({ hasText: "(expanded preview)" }).first().getAttribute("value"))
  const expanded = page.frame({ name: await expandedSelect.inputValue() })
  assert.ok(expanded, "Selected expanded Library frame is live")
  await expanded.locator("agentation-toolbar").waitFor({ state: "attached" })
  const viewport = await expanded.evaluate(() => ({ width: innerWidth, height: innerHeight, mounts: window.__libMounts }))
  assert.ok(viewport.width >= 360 && viewport.height >= 480)
  assert.equal(await countRuntimes(), 1)
  assert.ok(await page.getByText(/Expanded preview recreates state/).isVisible())
  await page.getByLabel("Annotations", { exact: true }).uncheck()
  await expanded.locator("agentation-toolbar").waitFor({ state: "detached" })
  assert.equal(await countRuntimes(), 0)
  assert.equal(await expanded.evaluate(() => window.__libMounts), viewport.mounts)
  passed("Base UI expanded popup exposes a usable selected child and disabling preserves its runtime")
  await page.waitForFunction(() => !document.querySelector('[data-studio-annotation-portal]')?.textContent.includes('editing viewport'))
  const natural = await expanded.evaluate(() => ({ width: innerWidth, height: innerHeight, mounts: window.__libMounts }))
  assert.ok(natural.height < viewport.height)
  await page.getByLabel("Annotations", { exact: true }).check()
  await expanded.locator("agentation-toolbar").waitFor({ state: "attached" })
  assert.equal(await expanded.evaluate(() => window.__libMounts), viewport.mounts)
  assert.ok((await expanded.evaluate(() => innerHeight)) >= 480)
  const removedTarget = await expandedSelect.inputValue()
  await page.getByRole("dialog").getByRole("button", { name: "Close", exact: true }).click()
  await page.locator("[data-studio-annotation-portal]").waitFor({ state: "detached" })
  const recoveredSelect = page.getByLabel("Annotation target")
  await recoveredSelect.waitFor()
  assert.equal(await recoveredSelect.inputValue(), removedTarget)
  const missingOption = recoveredSelect.locator("option").filter({ hasText: "Selected preview unavailable" })
  assert.equal(await missingOption.evaluate(option => option.disabled), true)
  assert.equal(await countRuntimes(), 0)
  await recoveredSelect.focus()
  assert.ok(await recoveredSelect.evaluate(select => select === document.activeElement))
  // Native typeahead works in macOS Chromium headless, whose closed-select arrow/Home keys do not change values.
  await recoveredSelect.press("s")
  await page.waitForFunction(() => document.querySelector('select[aria-label="Annotation target"]')?.value === "studio")
  await page.locator("agentation-toolbar").waitFor({ state: "attached" })
  assert.equal(await countRuntimes(), 1)
  passed("Expanded off/on resizes without remount; closing restores controls and keyboard Studio recovery")
  await page.getByLabel("Annotations", { exact: true }).uncheck()
  await page.locator("agentation-toolbar").waitFor({ state: "detached" })
  await page.reload()
  await page.getByRole("button", { name: "Feedback (2)", exact: true }).waitFor()
  assert.equal(await page.getByLabel("Annotations", { exact: true }).isChecked(), false)
  await page.getByRole("button", { name: "Feedback (2)", exact: true }).click()
  const restored = await page.getByLabel("Combined feedback Markdown").inputValue()
  assert.ok(restored.includes("Studio shell note.\nKeep this line verbatim."))
  assert.ok(restored.includes("Scope: shared"))
  passed("Feedback, scope and local off preference survive reload")
  await page.evaluate(() => {
    const key = Object.keys(localStorage).find(value => value.startsWith("studio-feedback/1:") && !value.endsWith(":enabled"))
    const original = JSON.parse(localStorage.getItem(key)).find(note => note.session.context.layer === "studio")
    const notes = Array.from({ length: 4 }, (_, index) => ({ ...original, key: `large-note-${index}`, annotation: { ...original.annotation, id: `large-note-${index}`, comment: "x".repeat(20000) } }))
    localStorage.setItem(key, JSON.stringify(notes)); localStorage.setItem(`${key}:enabled`, "true")
  })
  await page.goto(url)
  await page.getByRole("button", { name: "Feedback (4)", exact: true }).waitFor()
  await page.locator("agentation-toolbar").waitFor({ state: "attached" })
  await page.getByText(/saved notes exceed the marker-session limit/).waitFor()
  await page.getByRole("button", { name: "Feedback (4)", exact: true }).click()
  assert.equal(((await page.getByLabel("Combined feedback Markdown").inputValue()).match(/large-note-/g) ?? []).length >= 4, true)
  passed("Oversized accumulated feedback restores bounded markers with a notice and preserves every export note")
  assert.deepEqual(requests.filter(value => /^https?:/.test(value) && new URL(value).origin !== new URL(url).origin), [])
  passed("Supported workflow makes no external HTTP requests")
  assert.deepEqual(errors, [])
  passed("Zero page errors")
  const result = { checks, elapsedMs: Math.round(performance.now() - started), errors, viewport: "1440x1000", browser: await browser.version() }
  writeFileSync("annotations-acceptance-report.json", JSON.stringify(result, null, 2) + "\n")
  console.log(JSON.stringify(result, null, 2))
} finally {
  await browser.close()
  server.kill("SIGTERM")
}
